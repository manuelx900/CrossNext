#!/usr/bin/env python3
"""Generate the CrossNext open book and next-page mark, shared by boot and site.

The pixel grid follows the user-supplied light/dark CrossNext references.
One monochrome bitmap serves both display polarities. --check detects drift.
"""
import struct
import sys
import zlib
from pathlib import Path

SIZE = 120
# Coordinates on a 24 x 24 grid. Only axis-aligned pixel steps are used.
# Half-open horizontal runs, preserving exact 1-bit corners without a raster library.
ROWS = {3: [(3, 9), (15, 21)], 4: [(3, 9), (15, 21)], 5: [(1, 3), (9, 11), (13, 15), (21, 23)], 6: [(1, 3), (9, 11), (13, 15), (21, 23)], 7: [(1, 3), (11, 13), (15, 17), (21, 23)], 8: [(1, 3), (11, 13), (15, 18), (21, 23)], 9: [(1, 3), (11, 13), (16, 19), (21, 23)], 10: [(1, 3), (11, 13), (17, 20), (21, 23)], 11: [(1, 3), (11, 13), (16, 19), (21, 23)], 12: [(1, 3), (11, 13), (15, 18), (21, 23)], 13: [(1, 3), (11, 13), (15, 17), (21, 23)], 14: [(1, 3), (11, 13), (21, 23)], 15: [(1, 9), (11, 13), (15, 23)], 16: [(1, 9), (11, 13), (15, 23)], 17: [(9, 11), (13, 15)], 18: [(9, 11), (13, 15)], 19: [(11, 13)], 20: [(11, 13)]}

def is_ink(x,y):
 return any(a<=x//5<b for a,b in ROWS.get(y//5,[]))

def header():
 packed=[]
 for b in range(SIZE):
  for a0 in range(0,SIZE,8):
   byte=0
   for i in range(8):
    if not is_ink(SIZE-1-b,a0+i): byte|=1<<(7-i)
   packed.append(byte)
 rows=[packed[i:i+19] for i in range(0,len(packed),19)]
 body='\n'.join('    '+', '.join(f'0x{v:02x}' for v in row)+',' for row in rows)
 return '#pragma once\n\n#include <cstdint>\n\n// CrossNext: open book and next page. Generated by scripts/generate_logo.py.\nstatic constexpr uint8_t Logo120[] = {\n'+body+'\n};\n'

def svg(color='currentColor'):
 # Rectangles use the same source grid as the firmware bitmap.
 rects=''.join(f'<rect x="{a}" y="{y}" width="{b-a}" height="1"/>' for y,runs in ROWS.items() for a,b in runs)
 return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="CrossNext"><title>CrossNext</title><g fill="{color}">{rects}</g></svg>\n'

def png(size=SIZE):
 raw=bytearray()
 for y in range(size):
  raw.append(0)
  for x in range(size): raw.extend(b'\0\0\0\xff' if is_ink(x*SIZE//size,y*SIZE//size) else b'\0\0\0\0')
 def chunk(tag,payload):
  body=tag+payload
  return struct.pack('>I',len(payload))+body+struct.pack('>I',zlib.crc32(body))
 return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(bytes(raw),9))+chunk(b'IEND',b'')

def main():
 root=Path(__file__).resolve().parent.parent
 targets={'src/images/Logo120.h':header().encode(),'src/images/logo.svg':svg().encode(),'src/images/Logo120.png':png(),
          'site/assets/logo.svg':svg().encode(),'site/assets/logo-dark.svg':svg('#fff').encode(),'site/assets/favicon.svg':svg('#000').encode()}
 targets['site/assets/apple-touch-icon.png']=png(180)
 for rel in ['site/assets/icon-192.png','site/assets/icon-512.png']:
  if (root/rel).exists():targets[rel]=png(int(Path(rel).stem.split('-')[-1]))
 if '--check' in sys.argv:
  stale=[p for p,want in targets.items() if not (root/p).exists() or (root/p).read_bytes()!=want]
  for p in stale:print('stale:',p,file=sys.stderr)
  return bool(stale)
 for p,data in targets.items():
  (root/p).write_bytes(data)
  print('wrote',p)
 return 0
if __name__=='__main__':sys.exit(main())
