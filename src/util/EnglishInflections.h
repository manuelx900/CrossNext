inline const char* lemma(const char* word) {
  size_t first = 0, last = sizeof(entries) / sizeof(entries[0]);
  while (first < last) {
    const size_t mid = first + (last - first) / 2;
    const int order = std::strcmp(word, entries[mid].form);
    if (!order) return entries[mid].lemma;
    if (order < 0)
      last = mid;
    else
      first = mid + 1;
  }
  return nullptr;
}
