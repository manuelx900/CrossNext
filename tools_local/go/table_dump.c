#include <stdio.h>

#include "michi.h"

int main(void) {
  make_pat3set();
  init_zobrist_hashdata();
  puts("// Generated by tools_local/go/generate_tables.py from the engine's own builders.");
  puts("const Byte pat3set[8192] = {");
  for (int i = 0; i < 8192; ++i) {
    if (i % 24 == 0) printf("    ");
    printf("0x%02x,", (unsigned)pat3set[i]);
    if (i % 24 == 23 || i == 8191) putchar('\n');
  }
  puts("};\nconst ZobristHash zobrist_hashdata[ZOBRIST_HASH_SIZE][4] = {");
  for (int i = 0; i < ZOBRIST_HASH_SIZE; ++i) {
    printf("    {");
    for (int j = 0; j < 4; ++j) printf("0x%016llxULL,", zobrist_hashdata[i][j]);
    puts("},");
  }
  puts("};");
  return 0;
}
