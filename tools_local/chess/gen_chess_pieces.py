#!/usr/bin/env python3
"""Rasterise the vendored Apache-2.0 Chessnut pieces, preserving internal detail.
Development dependencies: resvg-py and Pillow. Run bin/clang-format-fix afterwards.
"""
from pathlib import Path
import io
import sys
from PIL import Image
import resvg_py
SIZE, SMALL, THRESHOLD = 48, 24, 190
PIECES = [("Pawn", "P"), ("Knight", "N"), ("Bishop", "B"), ("Rook", "R"), ("Queen", "Q"), ("King", "K")]
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets_local/pieces/chessnut"
OUT = ROOT / "src/apps_local/chess/ChessPieces.h"
def rasterise(svg, size):
    png = resvg_py.svg_to_bytes(svg_path=str(svg), width=size, height=size, background="white")
    im = Image.open(io.BytesIO(png)).convert("L")
    return [[im.getpixel((x,y)) < THRESHOLD for x in range(size)] for y in range(size)]
def silhouette(mask):
    """Fill enclosed white details to form an opaque mask for either colour."""
    size = len(mask)
    outside = [[False] * size for _ in range(size)]
    stack = []
    for i in range(size):
        for x, y in ((i, 0), (i, size - 1), (0, i), (size - 1, i)):
            if not mask[y][x] and not outside[y][x]:
                outside[y][x] = True
                stack.append((x, y))
    while stack:
        x, y = stack.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < size and 0 <= ny < size and not mask[ny][nx] and not outside[ny][nx]:
                outside[ny][nx] = True
                stack.append((nx, ny))
    return [[not outside[y][x] for x in range(size)] for y in range(size)]


def ink_bounds(mask):
    """Left edge and width of the actual ink.

    The captured strips advanced by a fixed stride, which suited pawns and made
    a queen collide with the rook beside it: every bitmap is 24px wide but the
    ink inside it is not. Packing by real ink width is the only way to get an
    even optical gap between shapes of different widths.
    """
    size = len(mask)
    left, right = size, -1
    for y in range(size):
        for x in range(size):
            if mask[y][x]:
                left = min(left, x)
                right = max(right, x)
    if right < 0:
        return 0, 0
    return left, right - left + 1


def to_bytes(mask):
    size = len(mask)
    row_bytes = (size + 7) // 8
    data = []
    for y in range(size):
        for b in range(row_bytes):
            byte = 0
            for bit in range(8):
                x = b * 8 + bit
                if x < size and mask[y][x]:
                    byte |= 1 << (7 - bit)
            data.append(byte)
    return data


def format_array(name, data):
    lines = [f"inline constexpr uint8_t {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + " ".join(f"0x{v:02X}," for v in data[i : i + 12]))
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = ["#pragma once", "#include <cstdint>", "// GENERATED by tools_local/chess/gen_chess_pieces.py. Do not edit.",
             "// Chessnut by Alexis Luengas, Apache-2.0; assets_local/pieces/chessnut/NOTICE.",
             "// Row-major MSB-first, bit set = ink. Mask is the opaque outer silhouette.",
             "namespace chessart {", "constexpr int kPieceSize = 48, kSmallPieceSize = 24;"]
    sheet = Image.new("L", (48*6,48*2),255)
    bounds = []
    for i,(name,code) in enumerate(PIECES):
        for size,suffix in [(SIZE,""),(SMALL,"Small")]:
            light = rasterise(SRC / f"w{code}.svg",size)
            dark = rasterise(SRC / f"b{code}.svg",size)
            mask = silhouette([[light[y][x] or dark[y][x] for x in range(size)] for y in range(size)])
            for label,bits in [("Solid",dark),("Light",light),("Mask",mask)]:
                parts += [format_array(f"k{name}{label}{suffix}",to_bytes(bits)), ""]
            if size == SMALL: bounds.append(ink_bounds(mask))
            else:
                for row,bits in enumerate([light,dark]):
                    for y in range(size):
                        for x in range(size):
                            if bits[y][x]: sheet.putpixel((i*48+x,row*48+y),0)
    parts += ["struct SmallInk { uint8_t left, width; };", "constexpr SmallInk kSmallInk[7] = {{0,0}," + ",".join("{%d,%d}"%b for b in bounds) + "};"]
    for func,label in [("maskFor","Mask"),("blackFor","Solid"),("whiteFor","Light")]:
        parts += [f"inline const uint8_t* {func}(int type, bool small) {{", "  switch(type) {"]
        for n,(name,_) in enumerate(PIECES,1): parts.append(f"    case {n}: return small ? k{name}{label}Small : k{name}{label};")
        parts += ["    default: return nullptr;", "  }", "}"]
    parts += ["}"]
    OUT.write_text("\n".join(parts)+"\n")
    if len(sys.argv)>1: sheet.resize((sheet.width*3,sheet.height*3),Image.Resampling.NEAREST).save(sys.argv[1])
    print("wrote", OUT)
if __name__ == "__main__": main()
