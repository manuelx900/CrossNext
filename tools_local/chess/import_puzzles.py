#!/usr/bin/env python3
"""Select and validate the bundled CC0 Lichess mating puzzles (development only)."""
import argparse
import csv
import io
import json
import re
from pathlib import Path
import urllib.request

import chess

ROOT = Path(__file__).resolve().parents[2]
URL = "https://database.lichess.org/lichess_db_puzzle.csv.zst"
TARGET = (400, 350, 250)


def compatible(fen, moves):
    board = chess.Board(fen)
    if not board.is_valid() or len(moves) not in (1, 3, 5):
        return False
    for ply, uci in enumerate(moves):
        if ply % 2 == 0 and any(move.promotion for move in board.legal_moves):
            return False
        move = chess.Move.from_uci(uci)
        if move.promotion or move not in board.legal_moves:
            return False
        board.push(move)
    return board.is_checkmate()


def select_catalogue():
    import zstandard
    groups = [[], [], []]
    seen = set()
    request = urllib.request.Request(URL, headers={"User-Agent": "CrossPlay-puzzle-import/1.0"})
    with urllib.request.urlopen(request, timeout=90) as response:
        with zstandard.ZstdDecompressor().stream_reader(response) as stream:
            for row in csv.DictReader(io.TextIOWrapper(stream, encoding="utf-8")):
                themes = row["Themes"].split()
                if not any(t in themes for t in ("mateIn1", "mateIn2", "mateIn3")):
                    continue
                rating = int(row["Rating"])
                group = 0 if rating <= 1400 else 1 if rating < 2000 else 2
                if len(groups[group]) == TARGET[group] or int(row["Popularity"]) < 80 or int(row["NbPlays"]) < 100:
                    continue
                if group == 1 and "mateIn1" in themes or group == 2 and "mateIn1" in themes:
                    continue
                board = chess.Board(row["FEN"])
                line = [chess.Move.from_uci(m) for m in row["Moves"].split()]
                if len(line) not in (2, 4, 6) or any(m.promotion for m in line):
                    continue
                if not board.is_valid() or line[0] not in board.legal_moves:
                    continue
                board.push(line[0])
                fen = board.fen()
                if fen.split(" ")[0] in seen:
                    continue
                if not compatible(fen, row["Moves"].split()[1:]):
                    continue
                seen.add(fen.split(" ")[0])
                groups[group].append({"id": row["PuzzleId"], "fen": fen, "moves": row["Moves"].split()[1:], "rating": rating})
                if sum(map(len, groups)) % 100 == 0:
                    print("Validated", [len(g) for g in groups], flush=True)
                if all(len(g) == count for g, count in zip(groups, TARGET)):
                    break
    assert [len(g) for g in groups] == list(TARGET)
    return {"source": URL, "license": "CC0-1.0", "groups": groups}


def pack(data):
    assert data["source"] == URL and data["license"] == "CC0-1.0"
    groups = data["groups"]
    assert [len(g) for g in groups] == list(TARGET)
    entries = [item for group in groups for item in group]
    assert all(re.fullmatch(r"[A-Za-z0-9]{5}", item["id"]) for item in entries)
    assert len({item["id"] for item in entries}) == 1000
    assert len({item["fen"].split()[0] for item in entries}) == 1000
    assert all(compatible(item["fen"], item["moves"]) for item in entries)
    for group, items in enumerate(groups):
        assert all(0 <= item["rating"] <= 65535 for item in items)
        assert all((0 if item["rating"] <= 1400 else 1 if item["rating"] < 2000 else 2) == group for item in items)
        assert group == 0 or all(len(item["moves"]) >= 3 for item in items)
    out = ROOT / "src/apps_local/chess/puzzles"
    out.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by tools_local/chess/import_puzzles.py from the CC0 Lichess database.', '#include "ChessPuzzleCore.h"', 'namespace chesspuzzle {', 'namespace {', 'constexpr Puzzle kPuzzles[kCount] = {']
    for group in groups:
        for item in group:
            board = chess.Board(item["fen"])
            packed = []
            for square in range(0, 64, 2):
                pair = 0
                for offset in range(2):
                    piece = board.piece_at(square + offset)
                    value = 0 if piece is None else piece.piece_type | (0 if piece.color else 8)
                    pair |= value << (offset * 4)
                packed.append(pair)
            moves = [chess.Move.from_uci(m) for m in item["moves"]]
            encoded = [m.from_square | m.to_square << 6 for m in moves]
            encoded += [0] * (5 - len(encoded))
            castle = int(board.has_kingside_castling_rights(chess.WHITE)) | int(board.has_queenside_castling_rights(chess.WHITE)) << 1 | int(board.has_kingside_castling_rights(chess.BLACK)) << 2 | int(board.has_queenside_castling_rights(chess.BLACK)) << 3
            lines.append('  {{%s}, {%s}, "%s", %d, %d, %d, %d, %s},' % (','.join(map(str, packed)), ','.join(map(str, encoded)), item['id'], item['rating'], castle, board.ep_square if board.ep_square is not None else -1, len(moves), 'true' if board.turn else 'false'))
    lines += ['};', '}  // namespace', 'const Puzzle* puzzle(int index) { return index >= 0 && index < kCount ? &kPuzzles[index] : nullptr; }', '}  // namespace chesspuzzle', '']
    (out / "ChessPuzzleData.cpp").write_text('\n'.join(lines), encoding='utf-8')
    print("Wrote 1000 unique, legal, checkmating lines", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true", help="Replace the catalogue from Lichess; requires progress migration/versioning")
    args = parser.parse_args()
    source = ROOT / "tools_local/chess/puzzles.json"
    data = select_catalogue() if args.refresh else json.loads(source.read_text(encoding="utf-8"))
    pack(data)
    if args.refresh:
        source.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
