from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[2]
head='#pragma once\n#include "../ui/ToyboxScreen.h"\n\n// One-bit reference illustrations; regenerated by tools_local/flashcards_art/generate.py.\nnamespace flashart {\n'
for p in sorted((root/'assets_local/flashcards').glob('*.png')):
 image=Image.open(p).convert('L');data=[]
 for y in range(image.height):
  for x in range(0,image.width,8):
   data.append(sum(128>>b for b in range(8) if x+b>=image.width or image.getpixel((x+b,y))>=128))
 name=p.stem
 head+=f'inline constexpr uint8_t {name}Bits[] = {{\n'
 head+='\n'.join('  '+','.join(f'0x{n:02x}' for n in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n'
 head+=f'inline constexpr freeink::ui::BitmapRef {name}{{{name}Bits, {image.width}, {image.height}, freeink::ui::BitmapFormat::Mask1, false}};\n'
head+='inline void draw(toybox::Screen& s, freeink::ui::Rect r, const freeink::ui::BitmapRef& art) {\n  s.target().bitmap(r, art, freeink::ui::BitmapMode::Contain, freeink::ui::Paint::solid(freeink::ui::Color::Black));\n}\n}  // namespace flashart\n'
(root/'src/apps_local/flashcards/FlashArt.h').write_text(head,encoding='utf-8',newline='\n')
