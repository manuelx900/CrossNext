"""Compile the original study-suite atlas into bounded, flash-resident BW1 art."""
from pathlib import Path
from PIL import Image
import argparse
ROOT=Path(__file__).resolve().parents[2]
source=ROOT/'assets_local/illustrations/study-atlas.png'
image=Image.open(source).convert('RGB')
parts=['// Generated by tools_local/illustrations/build_art.py.\n// clang-format off\n#pragma once\n#include <FreeInkUI.h>\nnamespace studyart {\n']
for row in range(2):
 for col in range(3):
  name=('hero' if row==0 else 'scene')+str(col)
  crop=image.crop((col*image.width//3,row*image.height//2,(col+1)*image.width//3,(row+1)*image.height//2))
  size=(192,192) if row==0 else (320,224)
  crop=crop.resize(size,Image.Resampling.LANCZOS).convert('L').convert('1')
  data=bytes(b^255 for b in crop.tobytes())
  parts.append(f'inline constexpr uint8_t {name}Bits[]={{\n')
  parts.extend('  '+','.join(f'0x{b:02x}' for b in data[n:n+24])+',\n' for n in range(0,len(data),24))
  parts.append(f'}};\ninline constexpr freeink::ui::BitmapRef {name}{{{name}Bits,{size[0]},{size[1]},freeink::ui::BitmapFormat::BW1}};\n')
parts.append('}\n// clang-format on\n')
output=ROOT/'src/apps_local/ui/StudyArt.h';content=''.join(parts)
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');options=parser.parse_args()
if options.check:
 assert output.read_text()==content,'Study art is stale'
elif not output.exists()or output.read_text()!=content:output.write_text(content,newline='\n')
print('Compiled six illustrations:',sum(192*192//8 if n<3 else 320*224//8 for n in range(6)),'flash bytes')
