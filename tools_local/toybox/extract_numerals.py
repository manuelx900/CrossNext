"""Extract original Jersey numeral bitmaps without rerasterizing the reviewed face."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[2]
s=(root/'src/apps_local/ui/fonts/toybox_64.h').read_text()
data=bytes(int(x,16) for x in re.findall(r'0x([0-9A-Fa-f]+)',re.search(r'toybox_64Bitmaps\[\d+\] = \{(.*?)\};',s,re.S)[1]))
glyphs=[list(map(int,g.split(','))) for g in re.findall(r'^\s*\{([-\d, \t]+)\},',re.search(r'toybox_64Glyphs\[\] = \{(.*?)\};',s,re.S)[1],re.M)]
chars=' %+,-./0123456789:HMNIS';packed=bytearray();rows=[]
for ch in chars:
 w,h,advance,left,top,count,offset=glyphs[ord(ch)-32];rows.append((ord(ch),w,h,(advance+8)//16,left,top,len(packed)));packed.extend(data[offset:offset+count])
out='''#pragma once
// Generated by tools_local/toybox/extract_numerals.py from the shipped Jersey 25
// cut (SIL OFL). Inline constants share one flash copy; no font cache or heap.
#include <cstdint>
namespace numerals {
struct Glyph { uint8_t code, width, height, advance; int16_t left, top; uint16_t offset; };
inline constexpr Glyph glyphs[] = {
'''+''.join('    {'+', '.join(map(str,g))+'},\n' for g in rows)+'''};
inline constexpr uint8_t bits[] = {
'''+''.join('    '+', '.join(f'0x{x:02x}' for x in packed[i:i+18])+',\n' for i in range(0,len(packed),18))+'''};
}  // namespace numerals
'''
(root/'src/apps_local/ui/fonts/Numerals.h').write_text(out);print(len(packed),'numeral bitmap bytes')
