"""Generate extra Lucide icons from vendored ISC SVGs. Dev dependencies: resvg-py, Pillow."""
from pathlib import Path
import io
import resvg_py
from PIL import Image

root = Path(__file__).resolve().parents[2]
parts = ['#pragma once', '#include <Icon.h>', '// GENERATED by tools_local/toybox/gen_extra_icons.py.',
         '// Lucide symbols and local reading symbols; see assets_local/extra-icons/NOTICE and LICENSE.']
for source in sorted((root / 'assets_local/extra-icons').glob('*.svg')):
    for size in (32, 64):
        im = Image.open(io.BytesIO(resvg_py.svg_to_bytes(svg_path=str(source), width=size, height=size, background='white'))).convert('L')
        values = []
        for y in range(size):
            for x in range(0, size, 8):
                values.append(sum((im.getpixel((x + n, y)) >= 180) << (7 - n) for n in range(8)))
        name = 'extra_' + source.stem.replace('-', '_') + '_' + str(size)
        parts += ['inline constexpr uint8_t ' + name + '_bits[] = {']
        parts += ['  ' + ', '.join('0x%02x' % v for v in values[n:n+16]) + ',' for n in range(0, len(values), 16)]
        parts += ['};', f'inline constexpr freeink::Icon {name} = {{{size}, {size}, {size//2}, {name}_bits}};']
(root / 'src/apps_local/ui/ExtraIcons.h').write_text('\n'.join(parts) + '\n')
