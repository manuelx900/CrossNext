from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[2]
head='#pragma once\n#include <cstring>\n\n#include "../ui/ToyboxScreen.h"\n\n// One-bit reference illustrations; regenerated by tools_local/murdle_art/generate.py.\nnamespace murdleart {\n'
for p in sorted((root/'assets_local/murdle').glob('*.png')):
 image=Image.open(p).convert('L');data=[]
 for y in range(image.height):
  for x in range(0,image.width,8):
   data.append(sum(128>>b for b in range(8) if x+b>=image.width or image.getpixel((x+b,y))>=128))
 name=p.stem
 head+=f'inline constexpr uint8_t {name}Bits[] = {{\n'
 head+='\n'.join('  '+','.join(f'0x{n:02x}' for n in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n'
 head+=f'inline constexpr freeink::ui::BitmapRef {name}{{{name}Bits, {image.width}, {image.height}, freeink::ui::BitmapFormat::Mask1, false}};\n'
manifest=json.loads((root/'assets_local/murdle/sprites.json').read_text(encoding='utf-8'))
for kind in ('weapons','places','motives'):
 entries=manifest[kind]
 head+='inline constexpr const freeink::ui::BitmapRef* '+kind+'[] = {'+','.join('&'+entry['symbol'] for entry in entries)+'};\n'
 head+='inline constexpr const char* '+kind+'Ids[] = {'+','.join('"'+entry['id']+'"' for entry in entries)+'};\n'
head+='''inline const freeink::ui::BitmapRef* motiveById(const char* id) {
  if (!id) return nullptr;
  for (unsigned i = 0; i < sizeof(motives) / sizeof(motives[0]); ++i)
    if (std::strcmp(id, motivesIds[i]) == 0) return motives[i];
  return nullptr;
}
'''
head+='inline void draw(toybox::Screen& s, freeink::ui::Rect r, const freeink::ui::BitmapRef& art) {\n  s.target().bitmap(r, art, freeink::ui::BitmapMode::Contain, freeink::ui::Paint::solid(freeink::ui::Color::Black));\n}\n}  // namespace murdleart\n'
(root/'src/apps_local/murdle/MurdleArt.h').write_text(head,encoding='utf-8',newline='\n')
