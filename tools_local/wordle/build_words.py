"""Generate the fixed flash word banks from the original curated vocabulary."""
from pathlib import Path
import argparse

if 'Import' in globals():
    Import('env')
    ROOT = Path(env.subst('$PROJECT_DIR'))
else:
    ROOT = Path(__file__).resolve().parents[2]


def generate(check=False):
    parts = ['// Generated by tools_local/wordle/build_words.py from the original curated text files.\n// clang-format off\n#pragma once\nnamespace localwordle::data {\n']
    total = 0
    for length in (4, 5, 6):
        words = (ROOT / f'assets_local/wordle/words-{length}.txt').read_text(encoding='utf-8').splitlines()
        if words != sorted(set(words)) or not words or any(len(w) != length or not w.isascii() or not w.isalpha() or not w.isupper() for w in words):
            raise SystemExit(f'Invalid {length}-letter bank')
        total += len(words)
        parts.append(f'inline constexpr char words{length}[][{length+1}] = {{\n' + ''.join(f'  "{w}",\n' for w in words) + '};\n')
    for length in (4, 5, 6):
        guesses = (ROOT / f'assets_local/wordle/guesses-{length}.txt').read_text(encoding='utf-8').splitlines()
        if guesses != sorted(set(guesses)) or any(len(w)!=length or not w.isascii() or not w.isalpha() or not w.isupper() for w in guesses):
            raise SystemExit('Invalid accepted guess dictionary')
        parts.append(f'inline constexpr char guesses{length}[][{length+1}] = {{\n' + ''.join(f'  "{w}",\n' for w in guesses) + '};\n')
    spanish = ['// SPDX-License-Identifier: MPL-2.0\n// Spanish RLA-ES dictionary data by Santiago Bosio and contributors.\n// Source and full license: assets_local/wordle/spanish/.\n// Generated by tools_local/wordle/build_words.py.\n// clang-format off\n#pragma once\nnamespace localwordle::data {\n']
    for length in (4, 5, 6):
        for kind in ('words', 'guesses'):
            words = (ROOT / f'assets_local/wordle/spanish/{kind}-{length}.txt').read_text().splitlines()
            if words != sorted(set(words)) or not words or any(len(w) != length or any(c < 'A' or c > '[' for c in w) for w in words):
                raise SystemExit('Invalid Spanish bank')
            spanish.append(f'inline constexpr char es{kind}{length}[][{length+1}] = {{\n' + ''.join(f'  "{w}",\n' for w in words) + '};\n')
    spanish.append('}\n// clang-format on\n')
    es_path = ROOT / 'src/apps_local/wordle/SpanishWords.generated.h'
    es_content = ''.join(spanish)
    es_previous = es_path.read_text() if es_path.exists() else None
    if check and es_previous != es_content: raise SystemExit('Spanish dictionary is stale')
    if not check and es_previous != es_content: es_path.write_text(es_content, newline='\n')
    parts.append('}\n// clang-format on\n')
    if total > 3000:
        raise SystemExit('The answer/guess bank must not exceed 3000 words')
    path = ROOT / 'src/apps_local/wordle/WordleWords.generated.h'
    content = ''.join(parts)
    previous = path.read_text(encoding='utf-8') if path.exists() else None
    if check:
        if previous != content:
            raise SystemExit('Word bank is stale or missing')
    elif previous != content:
        path.write_text(content, encoding='utf-8', newline='\n')
    print(f'Word banks: {total} everyday English words, lengths 4/5/6')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
elif 'Import' in globals():
    generate()
