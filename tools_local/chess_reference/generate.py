from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[2]
names = ['Pawn', 'Knight', 'Bishop', 'Rook', 'Queen', 'King']
out = '#pragma once\n#include <cstdint>\n\n// Generated by tools_local/chess_reference/generate.py from the supplied piece sheets.\n// clang-format off\nnamespace chessreference {\n'
for style in [1]:
 for colour in ['White', 'Black']:
  for name in names:
   im = Image.open(root/f'assets_local/chess_reference/{style}/{colour}{name}.png').convert('RGBA')
   for layer in ['Mask', 'Ink']:
    data = []
    for y in range(64):
     for x in range(0,64,8):
      value = 0
      for b in range(8):
       r,g,bl,a = im.getpixel((x+b,y))
       if a>=128 and (layer=='Mask' or r<128): value |= 128>>b
      data.append(value)
    ident = f'S{style}{colour}{name}{layer}'
    out += f'inline constexpr uint8_t {ident}[] = {{\n'
    out += '\n'.join('  '+','.join(f'0x{v:02x}' for v in data[n:n+24])+',' for n in range(0,len(data),24))+'\n};\n'
out += 'struct Piece { const uint8_t* mask; const uint8_t* ink; };\ninline constexpr Piece pieces[1][2][6] = {\n'
for style in [1]:
 out += '  {\n'
 for colour in ['White','Black']:
  out += '    {'+', '.join('{S'+str(style)+colour+name+'Mask,S'+str(style)+colour+name+'Ink}' for name in names)+'},\n'
 out += '  },\n'
out += '};\n}  // namespace chessreference\n// clang-format on\n'
(root/'src/apps_local/chess/ReferencePieces.h').write_text(out,encoding='utf-8',newline='\n')
