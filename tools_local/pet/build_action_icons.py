"""Pack the supplied PET action reference into four-level flash icons."""
from pathlib import Path
import hashlib
import json

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "REDISEÑOS/PET/assets/v6/iconos-acciones"
OUTPUT = ROOT / "src/apps_local/pet/PetActionIcons.h"


def main():
    metadata = json.loads((ASSETS / "crops.json").read_text("utf-8"))
    source_path = ASSETS / metadata["source"]
    with Image.open(source_path) as source:
        source = source.convert("L")
    size = metadata["size"]
    assert size % 4 == 0
    lines = ["#pragma once", "", "#include <cstdint>", "",
             "// Generated by tools_local/pet/build_action_icons.py from the supplied reference.",
             "// Two bits per pixel: black, dark gray, light gray, transparent.",
             "namespace petui::actionicons {", f"inline constexpr int SIZE = {size};", "// clang-format off"]
    for name, box in metadata["crops"].items():
        crop = source.crop(box)
        bounds = crop.point(lambda value: 255 if value < 150 else 0).getbbox()
        assert bounds, name
        crop = crop.crop(bounds)
        scaled = (max(1, round(crop.width * metadata["scale"])),
                  max(1, round(crop.height * metadata["scale"])))
        assert max(scaled) <= size, (name, scaled)
        crop = crop.resize(scaled, Image.Resampling.LANCZOS)
        canvas = Image.new("L", (size, size), 255)
        canvas.paste(crop, ((size - crop.width) // 2, (size - crop.height) // 2))
        levels = [min(3, (value + 42) // 85) for value in canvas.tobytes()]
        data = bytes(sum(levels[at + i] << (6 - i * 2) for i in range(4))
                     for at in range(0, len(levels), 4))
        preview = Image.new("L", (size, size))
        preview.putdata([value * 85 for value in levels])
        preview.save(ASSETS / (name.lower() + ".png"))
        lines.append(f"inline constexpr uint8_t {name}[] = {{")
        for at in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[at:at + 16]) + ",")
        lines.extend(["};", ""])
    lines.extend(["// clang-format on", "}  // namespace petui::actionicons", ""])
    OUTPUT.write_text("\n".join(lines), "utf-8")
    provenance = {"source": metadata["source"], "sha256": hashlib.sha256(source_path.read_bytes()).hexdigest(),
                  "origin": "User-supplied PET action-card reference", "generator": "tools_local/pet/build_action_icons.py",
                  "format": "2-bit grayscale; white is transparent; 44 by 44 pixels", "heap_bytes": 0,
                  "flash_pixel_bytes": size * size // 4 * len(metadata["crops"])}
    (ASSETS / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", "utf-8")
    print(f"Packed {len(metadata['crops'])} PET action icons: {provenance['flash_pixel_bytes']} flash bytes")


if __name__ == "__main__":
    main()
