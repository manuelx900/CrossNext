"""Render PET's editable care SVGs and pack their four-shade firmware icons."""

import argparse
import io
from pathlib import Path
import shutil
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "REDISEÑOS/PET/assets/v9/ui/care"
OUTPUT = ROOT / "src/apps_local/pet/PetCareActionIcons.h"
NAMES = ("food", "stroke", "rest", "clean", "health", "read")
SIZE = 64


def rasterize(path, sharp_module):
    if sharp_module:
        script = """const sharp=require(process.argv[1]);
sharp(process.argv[2],{density:384}).resize(256,256).flatten({background:'#fff'})
.png().toBuffer().then(b=>process.stdout.write(b)).catch(e=>{console.error(e);process.exit(1)});"""
        command = ["node", "-e", script, sharp_module, str(path)]
    else:
        renderer = shutil.which("rsvg-convert")
        if not renderer:
            raise SystemExit("Use rsvg-convert or pass --sharp-module with an installed sharp module path.")
        command = [renderer, "-w", "256", "-h", "256", str(path)]
    data = subprocess.run(command, check=True, capture_output=True).stdout
    rgba = Image.open(io.BytesIO(data)).convert("RGBA")
    paper = Image.new("RGBA", rgba.size, "white")
    paper.alpha_composite(rgba)
    return paper.convert("L").resize((SIZE, SIZE), Image.Resampling.LANCZOS)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sharp-module", help="Optional path to the installed sharp Node module.")
    args = parser.parse_args()
    lines = ["#pragma once", "", "#include <cstdint>", "",
             "// Generated by tools_local/pet/build_care_action_icons.py from the care SVGs.",
             "namespace petui::careactionicons {", f"inline constexpr int SIZE = {SIZE};", "// clang-format off"]
    for name in NAMES:
        image = rasterize(SOURCE / f"{name}.svg", args.sharp_module)
        values = [min(3, (value + 42) // 85) for value in image.tobytes()]
        quantized = Image.new("L", image.size)
        quantized.putdata([value * 85 for value in values])
        quantized.save(SOURCE / f"{name}.png")
        packed = bytearray(SIZE * SIZE // 4)
        for at, value in enumerate(values):
            packed[at // 4] |= value << (6 - (at % 4) * 2)
        lines.append(f"inline constexpr uint8_t {name.upper()}[] = {{")
        for at in range(0, len(packed), 16):
            lines.append("    " + ", ".join(f"0x{value:02x}" for value in packed[at:at + 16]) + ",")
        lines.append("};")
        lines.append(f"static_assert(sizeof({name.upper()}) == SIZE * SIZE / 4);")
    lines.extend(["// clang-format on", "}  // namespace petui::careactionicons", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Packed {len(NAMES)} care icons: {len(NAMES) * SIZE * SIZE // 4} flash bytes")


if __name__ == "__main__":
    main()
