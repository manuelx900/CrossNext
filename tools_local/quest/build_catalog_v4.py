"""Generate complete-outfit catalog identities and English/Spanish labels."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]


def build():
    data = json.loads((ROOT / 'assets_local/quest/catalog_v4/catalog.json').read_text(encoding='utf-8'))
    labels = {'body': data['outfits'], 'pet': data['pets'], 'aura': data['auras']}
    source = ['#pragma once\n#include <I18n.h>\n// Generated by tools_local/quest/build_catalog_v4.py.\n// clang-format off\nnamespace questcatalog {\n']
    translations = {'en': {}, 'es': {}}
    for group, items in labels.items():
        keys = []
        for n, item in enumerate(items):
            key = f'STR_QUEST_CATALOG_{group.upper()}_{n}'
            keys.append('StrId::' + key)
            for lang in translations:
                translations[lang][key] = item[lang]
        source.append('inline constexpr StrId ' + group + '[]={'+','.join(keys)+'};\n')
    source.append('}\n// clang-format on\n')
    (ROOT / 'src/apps_local/quest/QuestCatalog.h').write_text(''.join(source), encoding='utf-8', newline='\n')
    extra = {'STR_QUEST_CLOTHING': ('Clothing', 'Cuerpo'), 'STR_QUEST_AURA_SLOT': ('Aura', 'Aura'),
             'STR_QUEST_PET_SLOT': ('Pets', 'Pet'), 'STR_QUEST_AVAILABLE': ('Available', 'Disponible'),
             'STR_QUEST_ITEM_LEVEL': ('Lv %u', 'Nv %u'),
             'STR_QUEST_COMPLETE_OUTFIT': ('Complete outfit', 'Atuendo completo')}
    for key, values in extra.items():
        translations['en'][key], translations['es'][key] = values
    for lang, filename in (('en', 'english.yaml'), ('es', 'spanish.yaml')):
        path = ROOT / 'lib/I18n/translations' / filename
        lines = [line for line in path.read_text(encoding='utf-8').splitlines()
                 if not line.startswith('STR_QUEST_CATALOG_') and line.split(':', 1)[0] not in translations[lang]]
        text = '\n'.join(lines).rstrip() + '\n\n'
        text += ''.join(key + ': ' + json.dumps(value, ensure_ascii=False) + '\n' for key, value in translations[lang].items())
        path.write_text(text, encoding='utf-8', newline='\n')
    print('100 outfit, 50 aura, 50 pet names in English and Spanish')


if __name__ == '__main__':
    build()
