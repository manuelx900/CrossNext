"""Pack the nine campaign patron portraits as bounded resident monochrome icons."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'assets_local/quest/redesign/portraits'
NAMES=('liora','market','mara','iri','taren','nadir','orin','sera','aster')

def build():
 out=['#pragma once\n#include <Icon.h>\n// Generated by tools_local/quest/build_portraits.py.\n// clang-format off\nnamespace questportraits {\n']
 records=[]
 for name in NAMES:
  path=SOURCE/(name+'-source.png');source=Image.open(path).convert('RGBA')
  assert source.getchannel('A').getextrema()[0]==0,name
  bounds=source.getchannel('A').getbbox();assert bounds
  source=source.crop(bounds)
  source.thumbnail((92,108),Image.Resampling.LANCZOS)
  canvas=Image.new('RGBA',(96,112),'white');canvas.alpha_composite(source,((96-source.width)//2,(112-source.height)//2))
  icon=canvas.convert('L').point(lambda value:255 if value>=165 else 0,'1')
  icon.save(SOURCE/(name+'.png'));bits=icon.tobytes();assert len(bits)==1344 and 100<sum(8-byte.bit_count() for byte in bits)<8000
  out.append('inline constexpr uint8_t '+name+'Bits[]={\n')
  for at in range(0,len(bits),20):out.append(' '+','.join(f'0x{b:02x}' for b in bits[at:at+20])+',\n')
  out.append('};\ninline constexpr freeink::Icon '+name+'={96,112,56,'+name+'Bits};\n')
  records.append({'name':name,'sourceSha256':hashlib.sha256(path.read_bytes()).hexdigest(),'bitmapSha256':hashlib.sha256(bits).hexdigest(),'bytes':len(bits)})
 out.append('inline constexpr const freeink::Icon* ALL[]={'+','.join('&'+n for n in NAMES)+'};\n')
 out.append('inline constexpr uint8_t PATRON[]={0,1,2,3,4,5,6,7,8,0,0,0};\n')
 out.append('inline const freeink::Icon& forBook(unsigned book) { return *ALL[PATRON[book<12?book:0]]; }\n}\n// clang-format on\n')
 (ROOT/'src/apps_local/quest/QuestPortraits.h').write_text(''.join(out),'utf-8')
 (SOURCE/'packed.json').write_text(json.dumps({'width':96,'height':112,'portraitCount':9,'bitmapBytes':12096,'records':records},indent=2)+'\n','utf-8')
 print('Nine campaign portraits:12,096 static bitmap bytes; no SD update or dynamic image buffer')
if __name__=='__main__':build()
