"""Generate the translated path previews and complete saga versions."""

import json

MILESTONES = (0, 3, 6, 9, 10)
LANGUAGES = ("en", "es")


def load(root):
    data = json.loads((root / "assets_local/quest/campaign/paths.json").read_text(encoding="utf-8"))
    assert data["version"] == 2
    assert len(data["prologue"]) == 4 and len(data["sagas"]) == 12
    assert [row["id"] for row in data["paths"]] == list(range(120))
    assert all(len(saga["versions"]) == len(MILESTONES) for saga in data["sagas"])
    for lang in LANGUAGES:
        scenes = [row["approach"][lang] for row in data["paths"]]
        assert len(set(scenes)) == len(scenes)
        assert all(0 < len(scene.split()) <= 50 and "\n" not in scene for scene in scenes)
        recaps = [text[lang] for saga in data["sagas"] for text in saga["versions"]]
        opening = [part["text"][lang] for part in data["prologue"]]
        for passage in scenes + recaps + opening + [data["epilogue"][lang]]:
            assert passage and passage.strip() == passage and "%" not in passage
    return data


def generate(root, strings, story):
    def register(key, text):
        strings[key] = tuple(text[lang] for lang in LANGUAGES)
        return "StrId::" + key

    prefix = "STR_QUEST_CAM_JOURNEY2_"
    paths = [register(f"{prefix}APPROACH_{row['id']}", row["approach"]) for row in story["paths"]]
    versions = [
        "  {" + ", ".join(register(f"{prefix}SAGA_{book}_{threshold}", version)
                         for threshold, version in zip(MILESTONES, saga["versions"])) + "},\n"
        for book, saga in enumerate(story["sagas"])
    ]
    header = '#pragma once\n// Generated by tools_local/quest/scene_content.py.\n// clang-format off\n'
    header += '#include <I18n.h>\nnamespace questscene {\n'
    header += "inline constexpr StrId APPROACH[] = {\n  " + ",\n  ".join(paths) + ",\n};\n"
    header += f"inline constexpr StrId SAGA[][{len(MILESTONES)}] = {{\n" + "".join(versions) + "};\n"
    header += "static_assert(sizeof(APPROACH) / sizeof(APPROACH[0]) == 120);\n"
    header += "static_assert(sizeof(SAGA) / sizeof(SAGA[0]) == 12);\n}\n// clang-format on\n"
    (root / "src/apps_local/quest/QuestSceneData.h").write_text(header, encoding="utf-8")
