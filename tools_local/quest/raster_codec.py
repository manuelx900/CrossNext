"""Deterministic, lossless flash bitmap packing; no firmware image workspace."""
from collections import Counter
import heapq
import hashlib
import json
from pathlib import Path


def rle(data):
    out=bytearray();i=0
    while i<len(data):
        run=1
        while i+run<len(data) and data[i+run]==data[i] and run<128:run+=1
        if run>=3:
            out.extend((127+run,data[i]));i+=run
        else:
            start=i;i+=run
            while i<len(data) and i-start<128:
                count=1
                while i+count<len(data) and data[i+count]==data[i] and count<3:count+=1
                if count>=3:break
                i+=min(count,128-(i-start))
            out.append(i-start-1);out.extend(data[start:i])
    return bytes(out)


def compile_sheet(namespace,sprites,groups,script,report_path=None):
    from build_expansion_art import array
    compressed=[];predictors=[]
    for name,data,w,h in sprites:
        assert w%8==0 and 0<w<=280 and len(data)==w//8*h
        choices=[]
        for predictor,distance in ((0,0),(1,w//8),(2,w//4),(3,1)):
            delta=bytes(v^(data[i-distance] if distance and i>=distance else 0) for i,v in enumerate(data))
            choices.append((len(rle(delta)),predictor,rle(delta)))
        _,predictor,encoded=min(choices)
        compressed.append(encoded);predictors.append(predictor)
    counts=Counter(value for data in compressed for value in data)
    heap=[(n,value,256+value) for value,n in sorted(counts.items())]
    heapq.heapify(heap);nodes=[];order=256
    while len(heap)>1:
        a,_,left=heapq.heappop(heap);b,_,right=heapq.heappop(heap)
        node=len(nodes);nodes.append((left,right))
        heapq.heappush(heap,(a+b,order,node));order+=1
    codes={}
    def visit(node,bits,length):
        if node>=256:codes[node-256]=(bits,length);return
        left,right=nodes[node];visit(left,bits*2,length+1);visit(right,bits*2+1,length+1)
    root=heap[0][2];visit(root,0,0)
    assert max(n for bits,n in codes.values())<=24
    out=['#pragma once\n#include "../ui/FlashBitmap.h"\n// Generated by '+script+'.\n// clang-format off\nnamespace '+namespace+' {\nusing Sprite=flashbitmap::Sprite;\n']
    out.append('inline constexpr flashbitmap::Node codebook[]={'+','.join('{'+str(l)+','+str(r)+'}' for l,r in nodes)+'};\n')
    total=len(nodes)*4
    for (name,data,w,h),encoded in zip(sprites,compressed):
        packed=bytearray();buffer=0;length=0
        for value in encoded:
            code,n=codes[value];buffer=(buffer<<n)|code;length+=n
            while length>=8:
                length-=8;packed.append((buffer>>length)&255)
            buffer&=(1<<length)-1
        if length:packed.append((buffer<<(8-length))&255)
        assert len(packed)<=65535
        out.append(array(name,packed));total+=len(packed)
        # Check the generated bitstream without relying on the firmware decoder.
        actual=bytearray();node=root
        for value in packed:
            for shift in range(7,-1,-1):
                node=nodes[node][(value>>shift)&1]
                if node>=256:
                    actual.append(node-256);node=root
                    if len(actual)==len(encoded):break
            if len(actual)==len(encoded):break
        assert bytes(actual)==encoded
    lookup={name:(w,h,predictor) for (name,data,w,h),predictor in zip(sprites,predictors)}
    # Array declarations above keep the actual packed size available to C++.
    for group,names in groups.items():
        refs=[]
        for name in names:
            w,h,predictor=lookup[name]
            refs.append('{'+f'{name},codebook,sizeof({name}),{w},{h},{root},{predictor}'+'}')
        out.append('inline constexpr Sprite '+group+'[]={'+','.join(refs)+'};\n')
    out.append('}\n// clang-format on\n')
    raw={name:data for name,data,w,h in sprites}
    ordered=b''.join(raw[name] for names in groups.values() for name in names)
    report={'groups':{name:len(values) for name,values in groups.items()},
            'sha256':hashlib.sha256(ordered).hexdigest(),'decodedBytes':len(ordered),'packedBytes':total}
    report_path = report_path or Path(__file__).resolve().parents[2]/'assets_local/quest/expansion'/f'{namespace}-codec-check.json'
    report_path.write_text(json.dumps(report,indent=2))
    return ''.join(out),total
