"""Measure guardian artwork in the two shipped packs for hunt thumbnails."""
from pathlib import Path
from struct import unpack_from

ROOT = Path(__file__).resolve().parents[2]
PACKS = ROOT / "resources/apps/reading-adventure-v2"
OUTPUT = ROOT / "src/apps_local/quest/QuestHuntBounds.h"
WIDTH, HEIGHT = 248, 280


def bounds(data, index):
    offset, width, height, size, _ = unpack_from("<IHHII", data, 24 + 16 * index)
    stride = (width + 3) // 4
    assert (width, height, size) == (WIDTH, HEIGHT, stride * HEIGHT)
    left, top, right, bottom = width, height, 0, 0
    for y in range(height):
        for x in range(width):
            if (data[offset + y * stride + x // 4] >> (6 - 2 * (x % 4))) & 3:
                left, top, right, bottom = min(left, x), min(top, y), max(right, x + 1), y + 1
    assert left < right and top < bottom, index
    return left, top, right - left, bottom - top


def build(packs=PACKS, check=False):
    output = [
        "#pragma once", "", "#include <cstdint>", "",
        "// Generated by tools_local/quest/build_hunt_bounds.py.", "// clang-format off",
        "namespace questenemy {",
        "struct InkBounds { uint16_t x, y, width, height; };",
        f"inline constexpr int THUMBNAIL_WIDTH = {WIDTH}, THUMBNAIL_HEIGHT = {HEIGHT};",
        "inline constexpr InkBounds THUMBNAIL_INK[] = {",
    ]
    for name, indices in (("graphics", range(951, 990)), ("guardians", range(180))):
        data = (packs / f"{name}.bin").read_bytes()
        assert data[:8] == b"CNART003"
        for index in indices:
            output.append("    {" + ", ".join(map(str, bounds(data, index))) + "},")
    output += ["};", "}  // namespace questenemy", "// clang-format on", ""]
    rendered = "\n".join(output)
    if check:
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            raise ValueError("Stale hunt thumbnail bounds; run tools_local/quest/build_hunt_bounds.py with the updated packs")
    else:
        OUTPUT.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    build()
