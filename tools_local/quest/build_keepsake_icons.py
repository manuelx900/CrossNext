"""Archive original keepsake artwork and pack bounded monochrome UI illustrations."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets_local/quest/keepsakes'
BRIEF = ('Use case: illustration-story. One isolated tangible fantasy RPG inventory keepsake, '
         'charming hand inked black-and-white storybook / cozy chibi fantasy game prop. '
         'A fully illustrated recognizable crafted object, not a geometric line icon. '
         'Chunky dark black outer contours, large clean white surfaces and solid black accents, '
         'only minimal flat pale gray shading. No color, no crosshatching, no tiny filigree, '
         'no text, no lettering, no numbers, no labels, no frame, no scene or ground. '
         'Complete centered object, square composition, generous true transparent padding, no cropping. '
         'Must remain recognizable at 64 by 64 pixels on a monochrome e-ink reading adventure. ')

def initialize():
    if (SOURCE / 'jobs.json').exists():
        return
    SOURCE.mkdir(parents=True, exist_ok=True)
    rows = json.loads((ROOT / 'assets_local/quest/campaign/requests.json').read_text('utf8'))['requests']
    groups = {}
    for row in rows:
        noun = row['item']['es'].split()[0]
        key = noun + ('-' + row['shape'] if noun in ('Aguja', 'Fragmento') else '')
        if row['id'] == 3:
            key = 'Sello-hoja'
        groups.setdefault(key, []).append(row)
    jobs, mapping = [], [0] * 300
    for key, members in groups.items():
        n = len(jobs)
        sample = members[0]
        subject = sample['item']['en']
        if key == 'Sello':
            subject = 'a handmade wax library seal with its small antique wooden stamp handle, an open-book emblem'
        jobs.append({'id': f'K{n:03}', 'key': key, 'file': f'K{n:03}.png',
                     'sample': sample['item'], 'prompt': BRIEF + 'Subject: ' + subject + '.',
                     'requests': [row['id'] for row in members]})
        for row in members:
            mapping[row['id']] = n
    jobs.append({'id': 'coin', 'key': 'coin', 'file': 'coin.png', 'requests': [],
                 'prompt': BRIEF + 'Subject: exactly one round fantasy coin, viewed straight on with a tiny thickness edge on its lower right, bold rim and an embossed open book in its center. No stack of coins, no extra coins, no surrounding props.'})
    (SOURCE / 'jobs.json').write_text(json.dumps({'jobs': jobs, 'mapping': mapping}, ensure_ascii=False, indent=2), 'utf8')
    print('Prepared', len(jobs), 'distinct object illustrations')

def ingest(path):
    catalog = json.loads((SOURCE / 'jobs.json').read_text('utf8'))
    jobs = {job['id']: job for job in catalog['jobs']}
    for record in json.loads(Path(path).read_text('utf8')):
        job = jobs[record['id']]
        source = Path(record['source'])
        image = Image.open(source).convert('RGBA')
        assert image.width >= 512 and image.height >= 512
        assert image.getchannel('A').getextrema()[0] == 0, job['id']
        target = SOURCE / 'masters' / job['file']
        target.parent.mkdir(exist_ok=True)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if target.exists():
            assert hashlib.sha256(target.read_bytes()).hexdigest() == digest
        else:
            shutil.copy2(source, target)
        entry = dict(job, sha256=digest, source=str(source), tool='built-in image_gen', width=image.width, height=image.height)
        if 'prompt' in record: entry['prompt'] = record['prompt']
        target.with_suffix('.json').write_text(json.dumps(entry, ensure_ascii=False, indent=2), 'utf8')
    print('Archived', len(json.loads(Path(path).read_text('utf8'))), 'original images')

def build(output=None, preview=False):
    catalog = json.loads((SOURCE / 'jobs.json').read_text('utf8'))
    assert len(catalog['mapping']) == 300 and len(catalog['jobs']) == 134
    assert all(0 <= n < 133 for n in catalog['mapping'])
    assert len({j['id'] for j in catalog['jobs']}) == 134
    out = ['#pragma once\n#include <Icon.h>\n// Generated by tools_local/quest/build_keepsake_icons.py.\n// clang-format off\nnamespace questkeepsakeart {\n']
    records = []
    missing = []
    previews = SOURCE / 'previews'
    previews.mkdir(exist_ok=True)
    for job in catalog['jobs']:
        original = SOURCE / 'masters' / job['file']
        if not original.exists() and preview:
            missing.append(job['id'])
            continue
        provenance = json.loads(original.with_suffix('.json').read_text('utf8'))
        assert hashlib.sha256(original.read_bytes()).hexdigest() == provenance['sha256']
        image = Image.open(original).convert('RGBA')
        bounds = image.getchannel('A').point(lambda a: 255 if a >= 160 else 0).getbbox()
        assert bounds
        image = image.crop(bounds)
        image.thumbnail((88, 88), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', (96, 96), 'white')
        canvas.alpha_composite(image, ((96-image.width)//2, (96-image.height)//2))
        bitmap = canvas.convert('L').point(lambda value: 255 if value >= 165 else 0, '1')
        bitmap.save(previews / job['file'])
        bits = bitmap.tobytes()
        assert len(bits) == 1152
        ink = 96*96 - sum(byte.bit_count() for byte in bits)
        assert 40 < ink < 7000, (job['id'], ink)
        ident = 'object_' + job['id']
        out.append('inline constexpr uint8_t ' + ident + 'Bits[]={\n')
        for pos in range(0, len(bits), 24):
            out.append(' ' + ','.join(f'0x{b:02x}' for b in bits[pos:pos+24]) + ',\n')
        out.append('};\ninline constexpr freeink::Icon ' + ident + '={96,96,48,' + ident + 'Bits};\n')
        records.append({'id': job['id'], 'masterSha256': provenance['sha256'], 'bitmapSha256': hashlib.sha256(bits).hexdigest()})
    if missing:
        out.append('inline constexpr uint8_t pendingBits[1152]={' + ','.join(['255']*1152) + '};\n')
        out.append('inline constexpr freeink::Icon pending={96,96,48,pendingBits};\n')
        if 'coin' in missing: out.append('inline constexpr auto object_coin=pending;\n')
    assert len({record['bitmapSha256'] for record in records}) == len(records), 'Duplicated packed illustrations'
    out.append('inline constexpr const freeink::Icon* ITEMS[]={' + ','.join('&pending' if j['id'] in missing else '&object_'+j['id'] for j in catalog['jobs'][:-1]) + '};\n')
    out.append('inline constexpr uint8_t REQUEST_ITEM[]={' + ','.join(map(str,catalog['mapping'])) + '};\n')
    out.append('}\n// clang-format on\n')
    target = output or ROOT / 'src/apps_local/quest/QuestKeepsakeBitmaps.h'
    assert not preview or output, 'Partial previews must go to a separate cache file'
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text(''.join(out), 'utf8')
    report = target.with_suffix('.json') if preview else SOURCE/'packed.json'
    report.write_text(json.dumps({'width':96,'height':96,'count':len(records),'missing':missing,
        'bitmapBytes':len(records)*1152,'records':records},indent=2), 'utf8')
    print('Packed', len(records), 'illustrations;', len(records)*1152, 'static bytes; no SD changes or image workspace')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--initialize', action='store_true')
    parser.add_argument('--ingest', type=Path)
    parser.add_argument('--jobs', nargs=2, type=int)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--preview', action='store_true')
    args = parser.parse_args()
    if args.initialize: initialize()
    elif args.ingest: ingest(args.ingest)
    elif args.jobs:
        jobs = json.loads((SOURCE / 'jobs.json').read_text('utf8'))['jobs']
        print(json.dumps([j for j in jobs[args.jobs[0]:args.jobs[1]] if not (SOURCE/'masters'/j['file']).exists()],ensure_ascii=True))
    else: build(args.output,args.preview)
