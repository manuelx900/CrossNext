"""Pack the supplied shop-completion illustration into the existing 1-bit UI path."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets_local/quest/ui/shop-complete.png'
OUTPUT = ROOT / 'src/apps_local/quest/QuestShopCompleteArt.h'
image = Image.open(SOURCE).convert('RGBA')
bounds = image.getchannel('A').getbbox()
assert bounds
image = image.crop(bounds)
image.thumbnail((128, 128), Image.Resampling.LANCZOS)
canvas = Image.new('RGBA', (128, 128), 'white')
canvas.alpha_composite(image, ((128 - image.width) // 2, (128 - image.height) // 2))
bits = canvas.convert('L').convert('1', dither=Image.Dither.NONE).tobytes()
assert len(bits) == 2048
rows = [', '.join(f'0x{b:02x}' for b in bits[n:n + 19]) for n in range(0, len(bits), 19)]
OUTPUT.write_text('#pragma once\n#include <FreeInkUI.h>\n\nnamespace questshopart {\n'
                  '// Generated by tools_local/quest/build_shop_complete.py.\n'
                  'inline constexpr uint8_t COMPLETE_BITS[] = {\n    ' + ',\n    '.join(rows) + '};\n'
                  'inline constexpr freeink::ui::BitmapRef COMPLETE = {COMPLETE_BITS, 128, 128, '
                  'freeink::ui::BitmapFormat::Mask1};\n}  // namespace questshopart\n', 'utf8', newline='\n')
print('Shop illustration:', len(bits), 'bytes in Flash')
